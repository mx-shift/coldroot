//! The first ceremony: create the wrap key and its shares, generate the root
//! keys, and produce the first state disc.

use coldroot_core::{
    shares::{KEY_LEN, WrapKey},
    transcript::{Anchor, Confirmation, Event, Genesis, Operation, Participant, Transcript},
};
use jiff::Timestamp;
use rand_core::{OsRng, RngCore};
use yubihsm::{Capability, Client, Domain, asymmetric, object};

use crate::{
    CeremonyError, Console, Outcome, State, StoredKey, public_key, reset, sha256,
    verifier_committed,
};

/// A root key to generate. All keys are P-256, exportable only under wrap.
#[derive(Clone, Debug)]
pub struct KeySpec {
    pub id: u16,
    pub label: String,
}

#[derive(Clone, Debug)]
pub struct InitConfig {
    pub organization: String,
    /// A public value nobody could have known in advance; see [`Genesis`].
    pub public_anchor: Option<String>,
    pub participants: Vec<Participant>,
    pub threshold: u8,
    pub limit: u8,
    pub keys: Vec<KeySpec>,
}

/// The first share generation.
const FIRST_GENERATION: u32 = 1;

pub fn run(
    config: &InitConfig,
    client: &Client,
    console: &mut dyn Console,
) -> Result<Outcome, CeremonyError> {
    if config.keys.is_empty() {
        return Err(CeremonyError::NoKeys);
    }
    let mut nonce = [0u8; 32];
    OsRng.fill_bytes(&mut nonce);
    let genesis = Genesis {
        organization: config.organization.clone(),
        created: Timestamp::now(),
        nonce,
        public_anchor: config.public_anchor.clone(),
    };
    let mut transcript = Transcript::new(&Anchor::Genesis(genesis.clone()));
    transcript.append(Event::CeremonyStarted {
        participants: config.participants.clone(),
    })?;
    console.notice(&format!(
        "Genesis nonce, to be kept with the ceremony records: {}",
        hex::encode(nonce)
    ));

    let by = console.confirm("The machine clock matches an independent time source.")?;
    transcript.append(Event::Confirmed {
        by,
        what: Confirmation::ClockCorrect,
    })?;

    // The wrap key is sampled here, not generated by the HSM, because it has
    // to be a valid scalar to be shared; see `WrapKey::from_bytes`.
    let wrap_key = loop {
        let mut bytes = [0u8; KEY_LEN];
        OsRng.fill_bytes(&mut bytes);
        if let Some(key) = WrapKey::from_bytes(bytes) {
            break key;
        }
    };
    let (shares, verifier) = loop {
        match wrap_key.split(FIRST_GENERATION, config.threshold, config.limit, &mut OsRng) {
            Ok(split) => break split,
            // Only an unusable share set (probability ~2^-255) lands here.
            Err(coldroot_core::shares::ShareError::Unverified(_)) => continue,
            Err(e) => return Err(e.into()),
        }
    };
    transcript.append(verifier_committed(&verifier))?;
    for share in &shares {
        let by = console.issue_share(share)?;
        transcript.append(Event::Confirmed {
            by,
            what: Confirmation::ShareRecorded {
                custodian: share.index(),
            },
        })?;
    }

    coldroot_hsm::install_wrap_key(client, wrap_key.as_bytes())?;
    transcript.append(Event::Performed(Operation::InstallWrapKey))?;
    drop(wrap_key);

    let mut keys = Vec::with_capacity(config.keys.len());
    for spec in &config.keys {
        client.generate_asymmetric_key(
            spec.id,
            object::Label::from(spec.label.as_str()),
            Domain::DOM1,
            Capability::SIGN_ECDSA | Capability::EXPORTABLE_UNDER_WRAP,
            asymmetric::Algorithm::EcP256,
        )?;
        let public_key = public_key(client, spec.id)?;
        transcript.append(Event::Performed(Operation::GenerateKey {
            key_id: spec.id,
            label: spec.label.clone(),
            public_key_sha256: sha256(&public_key),
        }))?;
        console.notice(&format!(
            "Key {} ({}) public key SHA-256: {}",
            spec.id,
            spec.label,
            hex::encode(sha256(&public_key))
        ));
        let by = console.confirm("The public key fingerprint has been recorded.")?;
        transcript.append(Event::Confirmed {
            by,
            what: Confirmation::PublicKeyRecorded { key_id: spec.id },
        })?;
        keys.push(StoredKey {
            id: spec.id,
            label: spec.label.clone(),
            public_key,
            blob: Vec::new(),
        });
    }

    let ids: Vec<object::Id> = keys.iter().map(|k| k.id).collect();
    for (key, wrapped) in keys.iter_mut().zip(coldroot_hsm::backup(client, &ids)?) {
        key.blob = wrapped.message.into_vec();
        transcript.append(Event::Performed(Operation::ExportWrapped {
            key_id: key.id,
            blob_sha256: sha256(&key.blob),
        }))?;
    }

    transcript.append(reset(client)?)?;
    transcript.append(Event::CeremonyEnded)?;

    Ok(Outcome {
        state: State {
            genesis,
            verifier,
            keys,
            transcript_head: transcript.head(),
        },
        transcript: transcript.entries().to_vec(),
    })
}
